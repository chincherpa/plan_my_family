import { RRule } from "rrule";
import { createClient } from "@/lib/supabase/client";
import { useDataStore } from "@/lib/store/dataStore";
import type { AppointmentWithParticipants } from "@/lib/supabase/types";
import { startOfDay } from "@/lib/utils";
import { allDayEnd, expandAppointments, occurrenceDateKey, ruleAnchor } from "@/lib/utils/recurrence";
import { isSchoolHoliday, type HolidayRange } from "@/lib/utils/schoolHolidays";

/** single = this one, following = this and all later ones, series = all */
export type EditScope = "single" | "following" | "series";

type Supabase = ReturnType<typeof createClient>;

export type ActionResult = { ok: true } | { ok: false; error: string };

/** Undo handle for a deletion; null when the deletion cannot be undone. */
export type UndoFn = (() => Promise<ActionResult>) | null;

const fail = (error: string): ActionResult => ({ ok: false, error });
const OK: ActionResult = { ok: true };

/** Columns understood by the save_appointment_with_participants RPC. */
export function appointmentData(appt: AppointmentWithParticipants) {
  return {
    family_id: appt.family_id,
    title: appt.title,
    notes: appt.notes,
    owner_id: appt.owner_id,
    is_all_family: appt.is_all_family,
    is_event: appt.is_event,
    is_all_day: appt.is_all_day,
    start_time: appt.start_time,
    end_time: appt.end_time,
    travel_before_min: appt.travel_before_min,
    travel_after_min: appt.travel_after_min,
    vehicle_id: appt.vehicle_id,
    recurrence_rule: appt.recurrence_rule,
    recurrence_parent_id: appt.recurrence_parent_id,
    exception_date: appt.exception_date,
    skip_school_holidays: appt.skip_school_holidays,
  };
}

function participantData(appt: AppointmentWithParticipants) {
  return appt.participants.map((p) => ({ member_id: p.member_id, is_supervisor: p.is_supervisor }));
}

async function saveViaRpc(
  supabase: Supabase,
  data: ReturnType<typeof appointmentData>,
  participants: { member_id: string; is_supervisor: boolean }[],
  existingId?: string
): Promise<AppointmentWithParticipants | null> {
  const { data: saved, error } = await supabase.rpc("save_appointment_with_participants", {
    appointment_data: data,
    participant_data: participants,
    ...(existingId && { existing_appointment_id: existingId }),
  });
  if (error || !saved) {
    console.error("Termin konnte nicht gespeichert werden.", error);
    return null;
  }
  return saved as unknown as AppointmentWithParticipants;
}

/** Occurrence generated by a series rule (the appointment is the series' base row). */
export function isSeriesOccurrence(appt: AppointmentWithParticipants): boolean {
  return !!appt.recurrence_rule;
}

/**
 * Clicked occurrence is the first *visible* one of its series → "following"
 * equals "series". Occurrences skipped for school holidays or deleted via a
 * marker do not count; moved occurrences count on their new date.
 */
export function isFirstOccurrence(
  appt: AppointmentWithParticipants,
  occStart: Date,
  all: AppointmentWithParticipants[],
  holidays: HolidayRange[]
): boolean {
  if (!appt.recurrence_rule) return true;
  try {
    RRule.fromString(appt.recurrence_rule);
  } catch {
    return true;
  }
  const exceptions = all.filter((a) => a.recurrence_parent_id === appt.id);
  const cutKey = occurrenceDateKey(occStart);
  // Rules are anchored at local noon → compare by local day
  return !expandAppointments(
    [appt, ...exceptions],
    startOfDay(new Date(appt.start_time)),
    startOfDay(occStart),
    holidays
  ).some((occ) => occurrenceDateKey(occ.occurrenceStart) < cutKey);
}

/**
 * Cut the series off before the clicked occurrence: the rule gets an UNTIL
 * on the previous day, later exception rows are dropped. Never called for
 * the first occurrence (that is a whole-series operation).
 */
export async function endSeriesBefore(
  supabase: Supabase,
  parent: AppointmentWithParticipants,
  occStart: Date
): Promise<boolean> {
  const { appointments, removeAppointment, updateAppointment } = useDataStore.getState();
  const rule = RRule.fromString(parent.recurrence_rule!);
  const until = new Date(occStart);
  until.setDate(until.getDate() - 1);
  until.setHours(23, 59, 59, 0);
  const cut = new RRule({ ...rule.origOptions, count: null, until }).toString();
  const cutKey = occurrenceDateKey(occStart);

  // Exceptions first: modified instances render regardless of the rule, so
  // leftovers after a successful cut would duplicate the new series.
  // If the cut fails afterwards, the series simply keeps running.
  const { error: delError } = await supabase
    .from("appointments")
    .delete()
    .eq("recurrence_parent_id", parent.id)
    .gte("exception_date", cutKey);
  if (delError) return false;
  appointments
    .filter(
      (a) => a.recurrence_parent_id === parent.id && !!a.exception_date && a.exception_date >= cutKey
    )
    .forEach((a) => removeAppointment(a.id));

  const { error } = await supabase
    .from("appointments")
    .update({ recurrence_rule: cut })
    .eq("id", parent.id);
  if (error) return false;
  updateAppointment(parent.id, { recurrence_rule: cut });
  return true;
}

/**
 * Occurrences of `parent` before `occStart` that counted towards its COUNT
 * (occurrences skipped for school holidays did not count).
 */
export function occurrencesBefore(
  parent: AppointmentWithParticipants,
  occStart: Date,
  holidays: HolidayRange[]
): number {
  const cutKey = occurrenceDateKey(occStart);
  // Without COUNT: holidays stretch the series, the original COUNT would end
  // the enumeration too early. `between` is bounded by occStart.
  const rule = RRule.fromString(parent.recurrence_rule!);
  const open = new RRule({ ...rule.origOptions, count: null });
  // Compare by local date: rrule works in UTC, so across a DST switch the
  // clicked occurrence's rrule date can lie an hour before occStart
  return open
    .between(startOfDay(new Date(parent.start_time)), occStart, true)
    .map(occurrenceDateKey)
    .filter((key) => key < cutKey && !(parent.skip_school_holidays && isSchoolHoliday(key, holidays)))
    .length;
}

/**
 * Delete one occurrence, this and the following ones, or the whole series.
 * Returns an undo function where undoing is reliable (single appointment,
 * single occurrence); series-wide deletions return null.
 */
export async function deleteOccurrence(
  appt: AppointmentWithParticipants,
  occStart: Date | null,
  scope: EditScope
): Promise<{ result: ActionResult; undo: UndoFn }> {
  const supabase = createClient();
  const { appointments, addAppointment, updateAppointment, removeAppointment } =
    useDataStore.getState();
  const series = isSeriesOccurrence(appt);

  // Occurrence of a series → insert a deletion marker for this date only
  if (series && scope === "single" && occStart) {
    const durationMs = new Date(appt.end_time).getTime() - new Date(appt.start_time).getTime();
    const { data, error } = await supabase
      .from("appointments")
      .insert({
        family_id: appt.family_id,
        title: appt.title,
        start_time: occStart.toISOString(),
        end_time: new Date(occStart.getTime() + durationMs).toISOString(),
        recurrence_parent_id: appt.id,
        exception_date: occurrenceDateKey(occStart),
        is_deleted: true,
      })
      .select()
      .single();
    if (error || !data) return { result: fail("Termin konnte nicht gelöscht werden."), undo: null };
    const marker = { ...(data as AppointmentWithParticipants), participants: [] };
    addAppointment(marker);
    return {
      result: OK,
      undo: async () => {
        const { error } = await supabase.from("appointments").delete().eq("id", marker.id);
        if (error) return fail("Löschen konnte nicht rückgängig gemacht werden.");
        useDataStore.getState().removeAppointment(marker.id);
        return OK;
      },
    };
  }

  // Modified series instance → keep the row as deletion marker,
  // otherwise the original occurrence would reappear
  if (appt.recurrence_parent_id) {
    const { error } = await supabase
      .from("appointments")
      .update({ is_deleted: true })
      .eq("id", appt.id);
    if (error) return { result: fail("Termin konnte nicht gelöscht werden."), undo: null };
    updateAppointment(appt.id, { is_deleted: true });
    return {
      result: OK,
      undo: async () => {
        const { error } = await supabase
          .from("appointments")
          .update({ is_deleted: false })
          .eq("id", appt.id);
        if (error) return fail("Löschen konnte nicht rückgängig gemacht werden.");
        useDataStore.getState().updateAppointment(appt.id, { is_deleted: false });
        return OK;
      },
    };
  }

  // This and all following occurrences → end the series the day before
  if (
    series &&
    scope === "following" &&
    occStart &&
    !isFirstOccurrence(appt, occStart, appointments, useDataStore.getState().schoolHolidays)
  ) {
    if (!(await endSeriesBefore(supabase, appt, occStart))) {
      return { result: fail("Termine konnten nicht gelöscht werden."), undo: null };
    }
    return { result: OK, undo: null };
  }

  // Single appointment or whole series
  if (series) {
    await supabase.from("appointments").delete().eq("recurrence_parent_id", appt.id);
  }
  const { error } = await supabase.from("appointments").delete().eq("id", appt.id);
  if (error) return { result: fail("Termin konnte nicht gelöscht werden."), undo: null };
  appointments
    .filter((a) => a.recurrence_parent_id === appt.id)
    .forEach((a) => removeAppointment(a.id));
  removeAppointment(appt.id);

  if (series) return { result: OK, undo: null };
  // Plain appointment: recreate it from the snapshot (gets a new id)
  return {
    result: OK,
    undo: async () => {
      const saved = await saveViaRpc(supabase, appointmentData(appt), participantData(appt));
      if (!saved) return fail("Löschen konnte nicht rückgängig gemacht werden.");
      useDataStore.getState().addAppointment(saved);
      return OK;
    },
  };
}

export interface MoveTarget {
  start: Date;
  end: Date;
  /** New owner; null keeps the current one */
  ownerId: string | null;
}

/** Owner change: the new owner is no extra participant, "all family" ends. */
export function withOwner(appt: AppointmentWithParticipants, ownerId: string | null) {
  if (!ownerId || (ownerId === appt.owner_id && !appt.is_all_family)) {
    return { owner: { owner_id: appt.owner_id, is_all_family: appt.is_all_family }, participants: participantData(appt) };
  }
  return {
    owner: { owner_id: ownerId, is_all_family: false },
    participants: participantData(appt).filter((p) => p.member_id !== ownerId),
  };
}

/**
 * Move an occurrence to a new time and/or owner.
 * For "following" and "series" only time of day, duration and owner apply —
 * the series keeps its dates (same as the appointment form).
 */
export async function moveOccurrence(
  appt: AppointmentWithParticipants,
  occStart: Date,
  target: MoveTarget,
  scope: EditScope
): Promise<ActionResult> {
  const supabase = createClient();
  const { addAppointment, updateAppointment } = useDataStore.getState();
  const { owner, participants } = withOwner(appt, target.ownerId);
  const base = { ...appointmentData(appt), ...owner };

  if (!isSeriesOccurrence(appt)) {
    const saved = await saveViaRpc(
      supabase,
      { ...base, start_time: target.start.toISOString(), end_time: target.end.toISOString() },
      participants,
      appt.id
    );
    if (!saved) return fail("Termin konnte nicht verschoben werden.");
    updateAppointment(appt.id, saved);
    return OK;
  }

  const durationMs = target.end.getTime() - target.start.getTime();

  if (scope === "single") {
    // Exception row replaces the occurrence on its original date
    const saved = await saveViaRpc(
      supabase,
      {
        ...base,
        start_time: target.start.toISOString(),
        end_time: target.end.toISOString(),
        recurrence_rule: null,
        recurrence_parent_id: appt.id,
        exception_date: occurrenceDateKey(occStart),
      },
      participants
    );
    if (!saved) return fail("Termin konnte nicht verschoben werden.");
    addAppointment(saved);
    return OK;
  }

  // Keep the dates, take time of day from the target
  const timed = (day: Date) => {
    const s = new Date(day);
    s.setHours(target.start.getHours(), target.start.getMinutes(), 0, 0);
    const e = appt.is_all_day ? allDayEnd(s, target.start, target.end) : new Date(s.getTime() + durationMs);
    return { start: s, end: e };
  };

  const { appointments, schoolHolidays } = useDataStore.getState();
  if (scope === "following" && !isFirstOccurrence(appt, occStart, appointments, schoolHolidays)) {
    const rule = RRule.fromString(appt.recurrence_rule!);
    const { count } = rule.origOptions;
    const { start, end } = timed(occStart);
    const newRule = new RRule({
      ...rule.origOptions,
      dtstart: ruleAnchor(start),
      ...(count && { count: Math.max(count - occurrencesBefore(appt, occStart, schoolHolidays), 1) }),
    }).toString();
    const saved = await saveViaRpc(
      supabase,
      {
        ...base,
        start_time: start.toISOString(),
        end_time: end.toISOString(),
        recurrence_rule: newRule,
      },
      participants
    );
    if (!saved) return fail("Termine konnten nicht verschoben werden.");
    if (!(await endSeriesBefore(supabase, appt, occStart))) {
      // Roll back the new series so nothing is duplicated
      await supabase.from("appointments").delete().eq("id", saved.id);
      return fail("Serie konnte nicht geteilt werden.");
    }
    addAppointment(saved);
    return OK;
  }

  // Whole series: anchored at its original start date
  const { start, end } = timed(new Date(appt.start_time));
  const saved = await saveViaRpc(
    supabase,
    { ...base, start_time: start.toISOString(), end_time: end.toISOString() },
    participants,
    appt.id
  );
  if (!saved) return fail("Termine konnten nicht verschoben werden.");
  updateAppointment(appt.id, saved);
  return OK;
}

/** Copy one occurrence as a standalone appointment at the same time. */
export async function duplicateOccurrence(
  appt: AppointmentWithParticipants,
  occStart: Date,
  occEnd: Date
): Promise<ActionResult> {
  const supabase = createClient();
  const saved = await saveViaRpc(
    supabase,
    {
      ...appointmentData(appt),
      start_time: occStart.toISOString(),
      end_time: occEnd.toISOString(),
      recurrence_rule: null,
      recurrence_parent_id: null,
      exception_date: null,
      skip_school_holidays: false,
    },
    participantData(appt)
  );
  if (!saved) return fail("Termin konnte nicht dupliziert werden.");
  useDataStore.getState().addAppointment(saved);
  return OK;
}
